package module1programs;

public class OperatorsProgrm {
	
	static void add()
	
	{
		int a=100;
		int b=200;
		int c=a+b;
		System.out.println(c);
	}
	
	static void sub()
	{
		int c=100;
		int d=200;
		int f=c-d;
		System.out.println(f);
	}
	
	static void mul()
	{
		int c=100;
		int d=5;
		int f=c*d;
		System.out.println(f);
	}
	
	static void div()
	{
		int c=100;
		int d=5;
		int f=c/d;
		System.out.println(f);
	}
	
	static void mod()
	{
		int c=100;
		int d=5;
		int f=c%d;
		System.out.println(f);
	}
	
	public static void main(String[] args) 
	{
		add();
		sub();
		mul();
		div();
		mod();

	}

}
